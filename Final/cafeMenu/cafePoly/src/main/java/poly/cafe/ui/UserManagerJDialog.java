public void moveTo(int index) {
    int rowCount = tblUsers.getRowCount();
    if (rowCount == 0) return;

    if (index < 0) index = rowCount - 1;
    if (index >= rowCount) index = 0;

    tblUsers.clearSelection();
    tblUsers.setRowSelectionInterval(index, index);
    edit();
}

// ----------------------
// Hàm hỗ trợ kiểm tra form
// ----------------------
private boolean validateForm() {
    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());
    String confirm = new String(txtConfirm.getPassword());
    String fullname = txtFullname.getText().trim();

    // Kiểm tra rỗng
    if (username.isEmpty()) {
        XDialog.alert("Vui lòng nhập tên đăng nhập!");
        txtUsername.requestFocus();
        return false;
    }

    if (password.isEmpty()) {
        XDialog.alert("Vui lòng nhập mật khẩu!");
        txtPassword.requestFocus();
        return false;
    }

    if (confirm.isEmpty()) {
        XDialog.alert("Vui lòng xác nhận mật khẩu!");
        txtConfirm.requestFocus();
        return false;
    }

    if (fullname.isEmpty()) {
        XDialog.alert("Vui lòng nhập họ tên!");
        txtFullname.requestFocus();
        return false;
    }

    // Kiểm tra độ dài username
    if (username.length() < 4) {
        XDialog.alert("Tên đăng nhập phải có ít nhất 4 ký tự!");
        txtUsername.requestFocus();
        return false;
    }

    // Kiểm tra độ dài mật khẩu
    if (password.length() < 6) {
        XDialog.alert("Mật khẩu phải có ít nhất 6 ký tự!");
        txtPassword.requestFocus();
        return false;
    }

    // Kiểm tra xác nhận mật khẩu
    if (!password.equals(confirm)) {
        XDialog.alert("Mật khẩu xác nhận không khớp!");
        txtConfirm.requestFocus();
        return false;
    }

    // Kiểm tra họ tên không chứa số hoặc ký tự lạ
    if (!fullname.matches("^[\\p{L} .'-]+$")) {
        XDialog.alert("Họ tên không hợp lệ! Chỉ chứa chữ cái và khoảng trắng.");
        txtFullname.requestFocus();
        return false;
    }

    return true;
}



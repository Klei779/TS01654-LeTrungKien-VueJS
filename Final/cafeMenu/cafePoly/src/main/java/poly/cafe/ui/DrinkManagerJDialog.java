 boolean validateFormDrink() {
    String id = txtDrinkID.getText().trim();
    String name = txtDrinkName.getText().trim();
    String priceStr = txtUnitPrice.getText().trim();
    String category = (String) cboCategory.getSelectedItem();

    // Kiểm tra mã đồ uống rỗng
    if (id.isEmpty()) {
        MsgBox.alert(this, "Vui lòng nhập mã đồ uống!");
        txtDrinkID.requestFocus();
        return false;
    }

    // Mã đồ uống chỉ cho phép chữ và số, tối đa 10 ký tự
    if (!id.matches("^[a-zA-Z0-9]{1,10}$")) {
        MsgBox.alert(this, "Mã đồ uống chỉ gồm chữ và số (tối đa 10 ký tự)!");
        txtDrinkID.requestFocus();
        return false;
    }

    // Kiểm tra tên đồ uống rỗng
    if (name.isEmpty()) {
        MsgBox.alert(this, "Vui lòng nhập tên đồ uống!");
        txtDrinkName.requestFocus();
        return false;
    }

    if (name.length() < 3) {
        MsgBox.alert(this, "Tên đồ uống phải có ít nhất 3 ký tự!");
        txtDrinkName.requestFocus();
        return false;
    }

    // Kiểm tra đơn giá
    if (priceStr.isEmpty()) {
        MsgBox.alert(this, "Vui lòng nhập đơn giá!");
        txtUnitPrice.requestFocus();
        return false;
    }

    try {
        double price = Double.parseDouble(priceStr);
        if (price < 0) {
            MsgBox.alert(this, "Đơn giá phải lớn hơn hoặc bằng 0!");
            txtUnitPrice.requestFocus();
            return false;
        }
    } catch (NumberFormatException e) {
        MsgBox.alert(this, "Đơn giá phải là một số hợp lệ!");
        txtUnitPrice.requestFocus();
        return false;
    }

    // Kiểm tra danh mục
    if (category == null || category.isEmpty()) {
        MsgBox.alert(this, "Vui lòng chọn danh mục!");
        cboCategory.requestFocus();
        return false;
    }

    // Kiểm tra trạng thái: phải chọn Sẵn có hoặc Hết hàng
    if (!chkAvailable.isSelected() && !chkOutOfStock.isSelected()) {
        MsgBox.alert(this, "Vui lòng chọn trạng thái: Sẵn có hoặc Hết hàng!");
        return false;
    }

    // Nếu cả hai checkbox được chọn, cũng không hợp lệ
    if (chkAvailable.isSelected() && chkOutOfStock.isSelected()) {
        MsgBox.alert(this, "Chỉ được chọn một trong hai trạng thái: Sẵn có hoặc Hết hàng!");
        return false;
    }

    return true;
}


    public void fillCategories() {
        DefaultComboBoxModel<String> cboModel = new DefaultComboBoxModel<>();
        CategoryDAO dao = new CategoryDAO();
        try {
            List<Category> list = dao.selectAll();
            for (Category category : list) {
                cboModel.addElement(category.getName());
            }
            ListBoxCategory.setModel(cboModel);
            cboCategory.setModel(cboModel);
        } catch (Exception e) {
            MsgBox.alert(this, "Loi truy van du lieu");
        }
    }

    void fillTableByCategory() {
        DefaultTableModel model = (DefaultTableModel) tblDrink.getModel();
        model.setRowCount(0);

        CategoryDAO cdao = new CategoryDAO();
        String categoryName = ListBoxCategory.getSelectedValue();
        String id = cdao.getCategoryIdByName(categoryName);

        try {
            List<Drink> list = dao.selectAllCategoryID(id);
            for (Drink d : list) {
                Object[] row = {
                    d.getId(),
                    d.getName(),
                    String.format("$%.1f", d.getUnitPrice()),
                    String.format("%.0f%%", d.getDiscount() * 100),
                    d.isAvailable()
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy vấn dữ liệu");
        }
    }

    void clearForm() {
        txtDrinkID.setText("");
        txtDrinkName.setText("");
        txtUnitPrice.setText("");
        sldDiscount.setValue(0);
        lblDiscount.setText("0%");
        cboCategory.setSelectedIndex(0);
        chkAvailable.setSelected(false);
        chkOutOfStock.setSelected(false);
    }

    Drink getForm() {
        Drink d = new Drink();
        d.setId(txtDrinkID.getText());
        d.setName(txtDrinkName.getText());
        d.setUnitPrice(Double.parseDouble(txtUnitPrice.getText()));
        d.setDiscount(sldDiscount.getValue() / 100.0);
        d.setAvailable(chkAvailable.isSelected());

        CategoryDAO cdao = new CategoryDAO();
        String categoryName = (String) cboCategory.getSelectedItem();
        d.setCategoryId(cdao.getCategoryIdByName(categoryName));

        return d;
    }

    void setForm(Drink d) {
        txtDrinkID.setText(d.getId());
        txtDrinkName.setText(d.getName());
        txtUnitPrice.setText(String.valueOf(d.getUnitPrice()));
        sldDiscount.setValue((int) (d.getDiscount() * 100));
        lblDiscount.setText(String.format("%d%%", sldDiscount.getValue()));
        chkAvailable.setSelected(d.isAvailable());
        chkOutOfStock.setSelected(!d.isAvailable());

        CategoryDAO cdao = new CategoryDAO();
        String categoryName = cdao.getCategoryIdByName(d.getCategoryId());
        cboCategory.setSelectedItem(categoryName);
    }

   void insert() {
    if (!validateFormDrink()) return;
    Drink d = getForm();
    try {
        dao.insert(d);
        fillTableByCategory();
        MsgBox.alert(this, "Thêm mới thành công!");
    } catch (Exception e) {
        MsgBox.alert(this, "Thêm mới thất bại!");
        e.printStackTrace();
    }
}

void update() {
    if (!validateFormDrink()) return;
    Drink d = getForm();
    try {
        dao.update(d);
        fillTableByCategory();
        MsgBox.alert(this, "Cập nhật thành công!");
    } catch (Exception e) {
        MsgBox.alert(this, "Cập nhật thất bại!");
        e.printStackTrace();
    }
}


    void delete() {
        String id = txtDrinkID.getText();
        try {
            dao.delete(id);
            fillTableByCategory();
            MsgBox.alert(this, "Xóa thành công!");
        } catch (Exception e) {
            MsgBox.alert(this, "Xóa thất bại!");
            e.printStackTrace();
        }
    }


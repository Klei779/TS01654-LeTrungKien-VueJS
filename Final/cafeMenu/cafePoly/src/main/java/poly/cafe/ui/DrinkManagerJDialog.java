    void btnSelectAll() {
        DefaultTableModel model = (DefaultTableModel) tblDrink.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            model.setValueAt(true, i, 5); // cột checkbox
        }
    }

    void btnUnselectAll() {
        DefaultTableModel model = (DefaultTableModel) tblDrink.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            model.setValueAt(false, i, 5); // cột checkbox
        }
    }

    void btnDeleteSelected() {
        DefaultTableModel model = (DefaultTableModel) tblDrink.getModel();
        try {
            for (int i = model.getRowCount() - 1; i >= 0; i--) {
                Boolean selected = (Boolean) model.getValueAt(i, 5);
                if (selected != null && selected) {
                    String id = (String) model.getValueAt(i, 0);
                    dao.delete(id); // xóa trong database
                    model.removeRow(i); // xóa trên bảng
                }
            }
            MsgBox.alert(this, "Xóa các mục chọn thành công!");
            fillTableByCategory(); // load lại bảng sau khi xóa
        } catch (Exception e) {
            MsgBox.alert(this, "Xóa các mục chọn thất bại!");
            e.printStackTrace();
        }
    }


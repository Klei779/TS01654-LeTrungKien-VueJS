    private void updateBill() {
        try {
            Long id = Long.valueOf(txtCardId2.getText());
            String cardId = txtId2.getText();
            String user = txtUser.getText();
            Date checkin = XDate.parse(txtBegin2.getText(), "dd/MM/yyyy");
            Date checkout = XDate.parse(txtEnd2.getText(), "dd/MM/yyyy");
            String status = getTrangThai();

            Bill bill = new Bill(id, cardId, checkin, checkout, status, user);
            daoBill.update(bill);
            MsgBox.alert(this, "Cập nhật phiếu thành công!");
            fillTableBill();
        } catch (NumberFormatException e) {
            MsgBox.alert(this, "Cập nhật phiếu thất bại!");
        }
    }


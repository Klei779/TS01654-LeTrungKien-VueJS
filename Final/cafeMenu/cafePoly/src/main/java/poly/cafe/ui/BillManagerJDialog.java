    private String getTrangThai() {
        if (rdnServicing.isSelected()) {
            return "Servicing";
        }
        if (rdnCompleted.isSelected()) {
            return "Completed";
        }
        if (rdnCanceled.isSelected()) {
            return "Canceled";
        }
        return "";
    }


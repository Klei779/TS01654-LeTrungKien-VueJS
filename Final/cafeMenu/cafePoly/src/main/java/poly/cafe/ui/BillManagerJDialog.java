    private boolean validateForm() {
        // Mã phiếu không để trống
        if (txtCardId2.getText().trim().isEmpty()) {
            MsgBox.alert(this, "Vui lòng nhập mã phiếu.");
            txtCardId2.requestFocus();
            return false;
        }

        // Thẻ số: không để trống, là số nguyên dương
        String cardId = txtId2.getText().trim();
        if (cardId.isEmpty()) {
            MsgBox.alert(this, "Vui lòng nhập thẻ số.");
            txtId2.requestFocus();
            return false;
        }
        if (!cardId.matches("\\d+")) {
            MsgBox.alert(this, "Thẻ số phải là số nguyên dương.");
            txtId2.requestFocus();
            return false;
        }

        // Người dùng: không để trống, độ dài tối thiểu 3 ký tự
        String user = txtUser.getText().trim();
        if (user.isEmpty()) {
            MsgBox.alert(this, "Vui lòng nhập tên người dùng.");
            txtUser.requestFocus();
            return false;
        }
        if (user.length() < 3) {
            MsgBox.alert(this, "Tên người dùng phải từ 3 ký tự trở lên.");
            txtUser.requestFocus();
            return false;
        }

        // Trạng thái: phải chọn 1 trong 3
        if (!rdnServicing.isSelected() && !rdnCompleted.isSelected() && !rdnCanceled.isSelected()) {
            MsgBox.alert(this, "Vui lòng chọn trạng thái.");
            return false;
        }

        return true;
    }

    private boolean validateDate() {
        String beginText = txtBegin.getText().trim();
        String endText = txtEnd.getText().trim();

        if (beginText.isEmpty() || endText.isEmpty()) {
            MsgBox.alert(this, "Vui lòng nhập đầy đủ cả hai ngày.");
            return false;
        }

        try {
            Date begin = XDate.parse(beginText, "dd/MM/yyyy");
            Date end = XDate.parse(endText, "dd/MM/yyyy");

            if (begin.after(end)) {
                MsgBox.alert(this, "'Từ ngày' phải trước hoặc bằng 'Đến ngày'.");
                return false;
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Ngày nhập không đúng định dạng (dd/MM/yyyy).");
            return false;
        }

        return true;
    }

    void fillTableBill() {
        DefaultTableModel model = (DefaultTableModel) tblBill.getModel();
        model.setRowCount(0);

        try {
            Date begin = XDate.parse(txtBegin.getText(), "dd/MM/yyyy");
            Date end = XDate.parse(txtEnd.getText(), "dd/MM/yyyy");

            Calendar cal = Calendar.getInstance();
            cal.setTime(end);
            cal.set(Calendar.HOUR_OF_DAY, 23);
            cal.set(Calendar.MINUTE, 59);
            cal.set(Calendar.SECOND, 59);
            cal.set(Calendar.MILLISECOND, 999);
            end = cal.getTime();

            List<Bill> list = daoBill.findByTimeRange(begin, end);
            for (Bill cd : list) {
                Object[] row = {
                    cd.getId(), cd.getCardId(),
                    XDate.format(cd.getCheckin(), "dd/MM/yyyy"),
                    XDate.format(cd.getCheckout(), "dd/MM/yyyy"),
                    cd.getStatus(), cd.getUsername(), false // cột checkbox
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy vấn dữ liệu!");
        }

        autoResizeColumnWidth(tblBill);
    }

    public void autoResizeColumnWidth(JTable table) {
        final TableColumnModel columnModel = table.getColumnModel();
        for (int column = 0; column < table.getColumnCount(); column++) {
            int width = 50;
            for (int row = 0; row < table.getRowCount(); row++) {
                TableCellRenderer renderer = table.getCellRenderer(row, column);
                Component comp = table.prepareRenderer(renderer, row, column);
                width = Math.max(comp.getPreferredSize().width + 10, width);
            }

            TableCellRenderer headerRenderer = table.getTableHeader().getDefaultRenderer();
            Component headerComp = headerRenderer.getTableCellRendererComponent(
                    table, table.getColumnName(column), false, false, -1, column);
            width = Math.max(headerComp.getPreferredSize().width + 10, width);

            columnModel.getColumn(column).setPreferredWidth(width);
        }
    }

    public void selectTimeRange() {
        TimeRange range;
        switch (cboTimeRanges.getSelectedIndex()) {
            case 0 ->
                range = TimeRange.today();
            case 1 ->
                range = TimeRange.thisWeek();
            case 2 ->
                range = TimeRange.thisMonth();
            case 3 ->
                range = TimeRange.thisQuarter();
            case 4 ->
                range = TimeRange.thisYear();
            default ->
                range = TimeRange.today();
        }

        txtBegin.setText(XDate.format(range.getBegin(), "dd/MM/yyyy"));
        txtEnd.setText(XDate.format(range.getEnd(), "dd/MM/yyyy"));
        this.fillTableBill();
    }

    void btnSelectAll() {
        DefaultTableModel model = (DefaultTableModel) tblBill.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            model.setValueAt(true, i, 6);
        }
    }

    void btnUnselectAll() {
        DefaultTableModel model = (DefaultTableModel) tblBill.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            model.setValueAt(false, i, 6);
        }
    }

    void btnDeleteSelected() {
        DefaultTableModel model = (DefaultTableModel) tblBill.getModel();
        try {
            for (int i = model.getRowCount() - 1; i >= 0; i--) {
                Boolean selected = (Boolean) model.getValueAt(i, 6);
                if (Boolean.TRUE.equals(selected)) {
                    Long id = (Long) model.getValueAt(i, 0);
                    daoBill.delete(id);
                    model.removeRow(i);
                }
            }
            MsgBox.alert(this, "Xóa các mục chọn thành công!");
            fillTableBill();
        } catch (Exception e) {
            MsgBox.alert(this, "Xóa các mục chọn thất bại!");
        }
    }


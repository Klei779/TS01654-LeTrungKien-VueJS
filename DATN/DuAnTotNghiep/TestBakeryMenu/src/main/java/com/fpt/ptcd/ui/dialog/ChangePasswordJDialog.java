    public void init() {
        defaultEchoChar = txtNewPassword.getEchoChar();
    }

    @Override
    public void open() {
        this.setLocationRelativeTo(null);
    }

    @Override
    public void save() {
        String user = txtUsername.getText().trim();
        String pw = txtPassword.getText().trim(); // đã đổi từ getPassword() sang getText()
        String pw1 = new String(txtNewPassword.getPassword());
        String pw2 = new String(txtConfirmPassword.getPassword());

        if (user.isEmpty() || pw.isEmpty() || pw1.isEmpty() || pw2.isEmpty()) {
            MsgBox.alert(this, "Các thông tin không được bỏ trống");
            return;
        }

        if (!user.equalsIgnoreCase(XAuth.user.getFullname())) {
            MsgBox.alert(this, "Sai tên đăng nhập");
        } else if (!pw.equalsIgnoreCase(XAuth.user.getPassword())) {
            MsgBox.alert(this, "Sai mật khẩu");
        } else if (!pw1.equals(pw2)) {
            MsgBox.alert(this, "Xác nhận mật khẩu không đúng");
        } else {
            XAuth.user.setPassword(pw1);
            dao.update(XAuth.user);
            MsgBox.alert(this, "Cập nhật mật khẩu thành công");
            this.dispose();
        }
    }

    @Override
    public void close() {
        this.dispose();
    }

    @Override
    public void showPassword() {
        if (cbxPasswordVisible.isSelected()) {
            txtNewPassword.setEchoChar((char) 0);
            txtConfirmPassword.setEchoChar((char) 0);
        } else {
            txtNewPassword.setEchoChar(defaultEchoChar);
            txtConfirmPassword.setEchoChar(defaultEchoChar);
        }
    }

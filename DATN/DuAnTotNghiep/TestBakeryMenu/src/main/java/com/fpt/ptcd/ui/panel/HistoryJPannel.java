// ================== KHỞI TẠO BẢNG ==================

    private void init() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"Mã số", "Thẻ phiếu", "Thời điểm tạo", "Thời điểm thanh toán", "Phương thức", "Trạng thái", "Chọn"}, 0) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 6 ? Boolean.class : String.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 6;
            }
        };
        tblHistory.setModel(model);
        fillTable();
    }

// ================== ĐỔ DỮ LIỆU VÀO BẢNG ==================
    private void fillTable() {
        fillTable(billDAO.selectAll());
    }

    private void fillTable(List<Bill> list) {
        DefaultTableModel model = (DefaultTableModel) tblHistory.getModel();
        model.setRowCount(0);
        try {
            for (Bill b : list) {
                Object[] row = {
                    b.getId(),
                    b.getCardId() != null ? b.getCardId().toString() : "",
                    formatDate(b.getCheckIn()),
                    formatDate(b.getCheckOut()),
                    getPaymentMethodText(b.getPaymentMethod()),
                    b.getStatus() ? "Đã thanh toán" : "Chưa thanh toán",
                    false
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

// ================== CHỌN / BỎ CHỌN CHECKBOX ==================
    private void selectAll() {
        for (int i = 0; i < tblHistory.getRowCount(); i++) {
            tblHistory.setValueAt(true, i, 6);
        }
    }

    private void deselectAll() {
        for (int i = 0; i < tblHistory.getRowCount(); i++) {
            tblHistory.setValueAt(false, i, 6);
        }
    }

// ================== ĐIỀU HƯỚNG DÒNG ==================
    public void moveFirst() {
        moveTo(0);
    }

    public void movePrevious() {
        moveTo(tblHistory.getSelectedRow() - 1);
    }

    public void moveNext() {
        moveTo(tblHistory.getSelectedRow() + 1);
    }

    public void moveLast() {
        moveTo(tblHistory.getRowCount() - 1);
    }

    private void moveTo(int index) {
        int rowCount = tblHistory.getRowCount();
        if (rowCount == 0) {
            return;
        }
        if (index < 0) {
            index = rowCount - 1;
        } else if (index >= rowCount) {
            index = 0;
        }
        tblHistory.clearSelection();
        tblHistory.setRowSelectionInterval(index, index);
    }

// ================== HỖ TRỢ ==================
    private String formatDate(Date date) {
        return date == null ? "" : new SimpleDateFormat("dd/MM/yyyy").format(date);
    }

    private String getPaymentMethodText(Integer method) {
        return switch (method) {
            case 1 ->
                "Tiền mặt";
            case 2 ->
                "Chuyển khoản";
            default ->
                "Khác";
        };
    }


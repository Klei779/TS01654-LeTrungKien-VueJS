void init() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"ID cơ sở", "Tên", "Địa chỉ", "SĐT", "Ngày mở", "Trạng thái", "Chọn"}, 0) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 6 ? Boolean.class : String.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 6; // Chỉ checkbox được sửa
            }
        };
        tblGroundWork.setModel(model);
        fillTable();
    }

// ================== ĐỔ DỮ LIỆU VÀO BẢNG ==================
    void fillTable() {
        fillTable(dao.selectAll());
    }

    void fillTable(List<GroundWork> list) {
        DefaultTableModel model = (DefaultTableModel) tblGroundWork.getModel();
        model.setRowCount(0);
        try {
            for (GroundWork gw : list) {
                Object[] row = {
                    gw.getGroundWorkID(),
                    gw.getName(),
                    gw.getAddress(),
                    gw.getPhone(),
                    gw.getOpenDate() != null ? XDate.format(gw.getOpenDate(), "dd/MM/yyyy") : "",
                    gw.getStatus(),
                    false
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

// ================== THÊM CƠ SỞ ==================
    private void insertGroundWork() {
        GroundWorkAddJDialog dialog = new GroundWorkAddJDialog(
                (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this),
                true
        );
        dialog.setTitle("Thêm cơ sở");
        dialog.setVisible(true);

        // Sau khi đóng dialog, load lại bảng
        fillTable();
    }

// ================== CẬP NHẬT CƠ SỞ ==================
    private void updateGroundWork() {
        int selectedRow = tblGroundWork.getSelectedRow();
        if (selectedRow == -1) {
            MsgBox.alert(this, "Vui lòng chọn một dòng để sửa!");
            return;
        }

        int id = Integer.parseInt(tblGroundWork.getValueAt(selectedRow, 0).toString());
        GroundWork gw = dao.selectByID(id);
        if (gw == null) {
            MsgBox.alert(this, "Không tìm thấy dữ liệu với ID: " + id);
            return;
        }

        GroundWorkUpdateJDialog dialog = new GroundWorkUpdateJDialog(null, true);
        dialog.setTitle("Cập nhật cơ sở");
        dialog.setForm(gw);
        dialog.setVisible(true);

        fillTable(); // Sau khi dialog đóng, reload bảng
    }

// ================== XÓA CƠ SỞ ==================
    public void deleteGroundWork() {
        if (MsgBox.confirm(this, "Bạn có chắc muốn xóa các cơ sở đã chọn?")) {
            boolean deletedAny = false;
            for (int i = tblGroundWork.getRowCount() - 1; i >= 0; i--) {
                Boolean selected = (Boolean) tblGroundWork.getValueAt(i, 6);
                if (selected != null && selected) {
                    int id = Integer.parseInt(tblGroundWork.getValueAt(i, 0).toString());
                    try {
                        dao.delete(id);
                        deletedAny = true;
                    } catch (Exception e) {
                        MsgBox.alert(this, "Lỗi xóa ID " + id + ": " + e.getMessage());
                    }
                }
            }
            if (deletedAny) {
                MsgBox.alert(this, "Xóa thành công.");
            } else {
                MsgBox.alert(this, "Không có dòng nào được chọn để xóa.");
            }
            fillTable();
        }
    }

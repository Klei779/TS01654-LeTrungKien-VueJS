// ================== ĐIỀU HƯỚNG DÒNG ==================
    public void moveFirst() {
        moveTo(0);
    }

    public void movePrevious() {
        moveTo(tblGroundWork.getSelectedRow() - 1);
    }

    public void moveNext() {
        moveTo(tblGroundWork.getSelectedRow() + 1);
    }

    public void moveLast() {
        moveTo(tblGroundWork.getRowCount() - 1);
    }

    public void moveTo(int index) {
        int rowCount = tblGroundWork.getRowCount();
        if (rowCount == 0) {
            return;
        }
        if (index < 0) {
            index = rowCount - 1;
        } else if (index >= rowCount) {
            index = 0;
        }
        tblGroundWork.clearSelection();
        tblGroundWork.setRowSelectionInterval(index, index);
    }


    void init() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"Mã số", "Tên đăng nhập", "Mật khẩu", "Ảnh", "Vai trò", "Trạng thái", "Cơ sở", "Chọn"}, 0) {

            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 7 ? Boolean.class : String.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 7; // Chỉ cho tick chọn checkbox
            }
        };

        tblUser.setModel(model);
        fillTable();
    }

    void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblUser.getModel();
        model.setRowCount(0);

        try {
            List<com.fpt.ptcd.entity.User> list = dao.selectAll();
            for (com.fpt.ptcd.entity.User user : list) {
                Object[] row = {
                    user.getId(), // ID (Username)
                    user.getFullname(), // Họ tên
                    user.getPassword(), // Mật khẩu
                    user.getPhoto(), // Ảnh
                    user.isRole() ? "Manager" : "Staff", // Vai trò (boolean)
                    user.isEnabled() ? "Hoạt động" : "Vô hiệu", // Trạng thái (boolean)
                    user.getGroundWorkId(), // ID cơ sở
                    false // Cột checkbox chọn (nếu có)
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

    private void selectAll() {
        for (int i = 0; i < tblUser.getRowCount(); i++) {
            tblUser.setValueAt(true, i, 6);
        }
    }

    private void noSelectAll() {
        for (int i = 0; i < tblUser.getRowCount(); i++) {
            tblUser.setValueAt(false, i, 6);
        }
    }
    
        private void insert() {
        UserAddJDialog dialog = new UserAddJDialog(null, true);
        dialog.setTitle("Thêm hóa đơn");
        dialog.setLocationRelativeTo(null);
        dialog.setVisible(true);

        User u = dialog.getForm();
        if (u != null) {
            try {
                userDao.insert(u);
                MsgBox.alert(this, "Thêm hóa đơn thành công!");
                fillTable();
            } catch (Exception e) {
                MsgBox.alert(this, "Lỗi khi thêm hóa đơn: " + e.getMessage());
            }
        }
    }

    private void updateUser() {
        int selectedRow = tblUser.getSelectedRow();
        if (selectedRow == -1) {
            MsgBox.alert(this, "Vui lòng chọn một dòng để sửa!");
            return;
        }

        String id = tblUser.getValueAt(selectedRow, 0).toString();
        User user = userDao.selectByID(id);
        if (user == null) {
            MsgBox.alert(this, "Không tìm thấy người dùng với ID: " + id);
            return;
        }

        UserUpdateJDialog dialog = new UserUpdateJDialog(null, true);
        dialog.setTitle("Cập nhật người dùng");
        dialog.setForm(user);
        dialog.getBtnAdd().setText("Cập nhật"); // Đổi nút thành "Cập nhật"

        // Xóa listener cũ
        for (ActionListener al : dialog.getBtnAdd().getActionListeners()) {
            dialog.getBtnAdd().removeActionListener(al);
        }

        // Xử lý cập nhật khi nhấn nút
        dialog.getBtnAdd().addActionListener(evt -> {
            User updatedUser = dialog.getForm();
            if (updatedUser != null) {
                try {
                    userDao.update(updatedUser);
                    MsgBox.alert(dialog, "Cập nhật thành công!");
                    dialog.dispose();
                    fillTable(); // Cập nhật lại bảng
                } catch (Exception ex) {
                    MsgBox.alert(dialog, "Lỗi khi cập nhật: " + ex.getMessage());
                }
            }
        });

        dialog.setVisible(true);
    }

    public void delete() {
        if (MsgBox.confirm(this, "Bạn đang thực hiện chức năng xóa")) {
            boolean kq = false;
            for (int i = tblUser.getRowCount() - 1; i >= 0; i--) {
                Boolean checked = (Boolean) tblUser.getValueAt(i, 7);
                if (checked != null && checked) {
                    String id = tblUser.getValueAt(i, 0).toString(); // Lấy username
                    try {
                        dao.delete(id);
                        kq = true;
                    } catch (Exception e) {
                        MsgBox.alert(this, "Lỗi: " + e.getMessage());
                    }
                }
            }
            if (kq) {
                MsgBox.alert(this, "Xóa thành công");
            } else {
                MsgBox.alert(this, "Bạn chưa chọn dòng nào để xóa!");
            }
            fillTable();
        }
    }

    private void clearTableSelectionAndEdit() {
        TableCellEditor editor = tblUser.getCellEditor();
        if (editor != null) {
            editor.stopCellEditing();
        }
        tblUser.clearSelection();
        this.requestFocusInWindow();
    }


    public void moveTo(int index) {
        int rowCount = tblUser.getRowCount();
        if (rowCount == 0) {
            return;
        }
        if (index < 0) {
            index = rowCount - 1;
        } else if (index >= rowCount) {
            index = 0;
        }
        tblUser.clearSelection();
        tblUser.setRowSelectionInterval(index, index);

    }


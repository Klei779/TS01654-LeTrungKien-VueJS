    void init() {
        // 1. Khởi tạo model
        DefaultTableModel model = new DefaultTableModel(new Object[]{"Mã số", "Trạng thái", "Chọn"}, 0) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return (columnIndex == 2) ? Boolean.class : String.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 2;
            }
        };
        tblCard.setModel(model);

        // 2. Gán lại text cho các checkbox lọc trạng thái
        initCheckBoxText();

        // 3. Đổ dữ liệu ban đầu
        fillTable();
    }

// Đổ dữ liệu vào bảng
    public void fillTable() {
        try {
            List<Card> list = dao.selectAll();
            fillTableWithList(list);
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

// Đổ dữ liệu từ danh sách
    private void fillTableWithList(List<Card> list) {
        DefaultTableModel model = (DefaultTableModel) tblCard.getModel();
        model.setRowCount(0);
        for (Card cd : list) {
            model.addRow(new Object[]{cd.getId(), getStatusText(cd.getStatus()), false});
        }
    }

// Chuyển status int -> text
    private String getStatusText(int status) {
        switch (status) {
            case 0:
                return "OPERATING";
            case 1:
                return "LOST";
            case 2:
                return "ERROR";
            case 3:
                return "UNKNOWN";
            default:
                return "INVALID";
        }
    }
// ================== ĐỔI TÊN CHECKBOX ==================

    private void initCheckBoxText() {
        chkOperating.setText("OPERATING");
        chkLost.setText("LOST");
        chkError.setText("ERROR");
        chkUnknown.setText("UNKNOWN");
    }

// ================== TÌM KIẾM ==================
    private void Search() {
        try {
            List<Integer> selectedStatuses = new ArrayList<>();

            if (chkOperating.isSelected()) {
                selectedStatuses.add(0);
            }
            if (chkLost.isSelected()) {
                selectedStatuses.add(1);
            }
            if (chkError.isSelected()) {
                selectedStatuses.add(2);
            }
            if (chkUnknown.isSelected()) {
                selectedStatuses.add(3);
            }

            if (selectedStatuses.isEmpty()) {
                MsgBox.alert(this, "Vui lòng chọn ít nhất một trạng thái để tìm!");
                return;
            }

            List<Card> list = dao.selectByStatuses(selectedStatuses);
            fillTableWithList(list);
            MsgBox.alert(this, "Tìm thấy " + list.size() + " kết quả.");
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi tìm kiếm: " + e.getMessage());
        }
    }


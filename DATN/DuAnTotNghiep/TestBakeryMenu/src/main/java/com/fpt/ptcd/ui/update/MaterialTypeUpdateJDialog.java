    public void setForm(MaterialType c) {
        this.materialType = c;
        txtId.setText(String.valueOf(c.getId()));
        txtName.setText(c.getName());
    }

    public MaterialType getForm() {
        try {
            int id = Integer.parseInt(txtId.getText().trim());
            String name = txtName.getText().trim();

            if (name.isBlank()) {
                JOptionPane.showMessageDialog(this, "Tên danh mục không được để trống");
                return null;
            }

            return MaterialType.builder()
                    .Id(id)
                    .name(name)
                    .build();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "ID không hợp lệ");
            return null;
        }
    }


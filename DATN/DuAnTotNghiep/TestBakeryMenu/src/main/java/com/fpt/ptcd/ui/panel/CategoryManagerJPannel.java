    void init() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"Mã số", "Tên loại", "Chọn"}, 0) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 2 ? Boolean.class : String.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 2; // chỉ cho phép tick chọn
            }
        };
        tblCategory.setModel(model);
        fillTable();
    }

    void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblCategory.getModel();
        model.setRowCount(0);
        try {
            List<Category> list = dao.selectAll();
            for (Category c : list) {
                Object[] row = {
                    c.getId(),
                    c.getName(),
                    false
                };
                model.addRow(row);
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

    private void selectAll() {
        for (int i = 0; i < tblCategory.getRowCount(); i++) {
            tblCategory.setValueAt(true, i, 2);
        }
    }

    private void noSelectAll() {
        for (int i = 0; i < tblCategory.getRowCount(); i++) {
            tblCategory.setValueAt(false, i, 2);
        }
    }

    private void insertCategory() {
        CategoryAddJDialog dialog = new CategoryAddJDialog(null, true);
        dialog.setTitle("Thêm danh mục");
        dialog.setLocationRelativeTo(null);
        dialog.setVisible(true);

        Category category = dialog.getForm();
        if (category != null) {
            try {
                dao.insert(category);
                MsgBox.alert(this, "Thêm danh mục thành công!");
                fillTable();
            } catch (Exception e) {
                MsgBox.alert(this, "Lỗi khi thêm danh mục: " + e.getMessage());
            }
        }
    }

    private void deleteSelected() {
        DefaultTableModel model = (DefaultTableModel) tblCategory.getModel();
        try {
            for (int i = model.getRowCount() - 1; i >= 0; i--) {
                Boolean selected = (Boolean) model.getValueAt(i, 2);
                if (selected != null && selected) {
                    Integer id = Integer.valueOf(model.getValueAt(i, 0).toString());
                    dao.delete(id);
                    model.removeRow(i);
                }
            }
            JOptionPane.showMessageDialog(this, "Xóa thành công!");
            fillTable();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Xóa thất bại: " + e.getMessage());
        }
    }
    
private void updateCategory() {
    int selectedRow = tblCategory.getSelectedRow();
    if (selectedRow == -1) {
        MsgBox.alert(this, "Vui lòng chọn dòng để cập nhật!");
        return;
    }

    int id = Integer.parseInt(tblCategory.getValueAt(selectedRow, 0).toString());
    Category old = dao.selectByID(id);
    if (old == null) {
        MsgBox.alert(this, "Không tìm thấy dữ liệu!");
        return;
    }

    CategoryUpdateJDialog dialog = new CategoryUpdateJDialog(null, true);
    dialog.setForm(old);
    dialog.setLocationRelativeTo(null);
    dialog.setVisible(true);

    Category updated = dialog.getForm();
    if (updated != null) {
        dao.update(updated);
        MsgBox.alert(this, "Cập nhật thành công!");
        fillTable();
    }
}


    private void clearTableSelectionAndEdit() {
        TableCellEditor editor = tblCategory.getCellEditor();
        if (editor != null) {
            editor.stopCellEditing();
        }
        tblCategory.clearSelection();
        this.requestFocusInWindow();
    }

    public void moveFirst() {
        moveTo(0);
    }

    public void movePrevious() {
        moveTo(tblCategory.getSelectedRow() - 1);
    }

    public void moveNext() {
        moveTo(tblCategory.getSelectedRow() + 1);
    }

    public void moveLast() {
        moveTo(tblCategory.getRowCount() - 1);
    }

    public void moveTo(int index) {
        int rowCount = tblCategory.getRowCount();
        if (rowCount == 0) {
            return;
        }
        if (index < 0) {
            index = rowCount - 1;
        } else if (index >= rowCount) {
            index = 0;
        }
        tblCategory.clearSelection();
        tblCategory.setRowSelectionInterval(index, index);
    }


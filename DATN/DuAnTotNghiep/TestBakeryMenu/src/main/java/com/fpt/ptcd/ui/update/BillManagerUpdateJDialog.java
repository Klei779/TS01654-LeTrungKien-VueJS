// ======================== NẠP COMBOBOX ==========================
    private void fillComboBoxes() {
        cboUsers.removeAllItems();
        for (User u : userDAO.selectAll()) {
            cboUsers.addItem(u.getId());
        }

        cboCardId.removeAllItems();
        for (Card c : cardDAO.selectAll()) {
            cboCardId.addItem(String.valueOf(c.getId()));
        }

        cboGroundWork.removeAllItems();
        for (GroundWork g : groundWorkDAO.selectAll()) {
            cboGroundWork.addItem(String.valueOf(g.getGroundWorkID()));
        }

        cboPayment.setSelectedIndex(0);
        cboStatus.setSelectedIndex(0);
    }

// ======================== ĐỔ DỮ LIỆU FORM ==========================
    public void setForm(Bill bill, List<BillDetails> details) {
        if (bill == null || details == null || details.isEmpty()) {
            return;
        }

        BillDetails detail = details.get(0); // hiện tại chỉ hiển thị 1 bánh
        Bakery bakery = bakeryDAO.selectByID(detail.getBakeryId());

        txtId.setText(String.valueOf(bill.getId()));
        cboUsers.setSelectedItem(bill.getUsername());
        cboCardId.setSelectedItem(String.valueOf(bill.getCardId()));
        cboGroundWork.setSelectedItem(String.valueOf(bill.getGroundWorkId()));
        cboPayment.setSelectedIndex(bill.getPaymentMethod());
        cboStatus.setSelectedIndex(bill.getStatus() ? 1 : 0);
        dcCheckIn.setDate(bill.getCheckIn());
        dcCheckOut.setDate(bill.getCheckOut());

        if (bakery != null) {
            txtPrice.setText(String.valueOf(bakery.getUnitPrice()));
            txtFianlPrice.setText(String.format("%.2f",
                    bakery.getUnitPrice() * detail.getQuantity() * (1 - bakery.getDiscount())));
            txtName.setText(bakery.getName());
            slDiscount.setValue((int) (bakery.getDiscount() * 100));
            selectedBakeryId = bakery.getId();

            if (bakery.getPhoto() != null) {
                setPhoto(bakery.getPhoto()); // dùng riêng phương thức setPhoto
            }
        }

        spQuanity.setValue((double) detail.getQuantity());
    }

// ======================== LẤY DỮ LIỆU BILL ==========================
    public Bill getBill() {
        try {
            return Bill.builder()
                    .id(Integer.parseInt(txtId.getText().trim()))
                    .username(cboUsers.getSelectedItem().toString())
                    .cardId(Integer.parseInt(cboCardId.getSelectedItem().toString()))
                    .groundWorkId(Integer.parseInt(cboGroundWork.getSelectedItem().toString()))
                    .paymentMethod(cboPayment.getSelectedIndex())
                    .status(cboStatus.getSelectedIndex() == 1)
                    .checkIn(dcCheckIn.getDate())
                    .checkOut(dcCheckOut.getDate())
                    .build();
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi dữ liệu Bill: " + e.getMessage());
            return null;
        }
    }


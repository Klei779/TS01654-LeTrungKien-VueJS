    public List<BillDetails> getBillDetails() {
        try {
            if (selectedBakeryId == -1) {
                MsgBox.alert(this, "Chưa chọn bánh!");
                return null;
            }

            Number quantityVal = (Number) spQuanity.getValue();

            BillDetails detail = BillDetails.builder()
                    .billId(Integer.parseInt(txtId.getText().trim()))
                    .bakeryId(selectedBakeryId)
                    .quantity(quantityVal.doubleValue())
                    .unit("cái")
                    .build();

            return List.of(detail);
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi chi tiết hóa đơn: " + e.getMessage());
            return null;
        }
    }

// ======================== CẬP NHẬT ẢNH ==========================
    private void setPhoto(String fileName) {
        if (fileName != null) {
            ImageIcon icon = XImage.read(fileName); // bạn cần class XImage
            if (icon != null) {
                btnPhoto.setIcon(icon);
                btnPhoto.putClientProperty("fileName", fileName);
            }
        } else {
            btnPhoto.setIcon(null);
            btnPhoto.putClientProperty("fileName", null);
        }
    }


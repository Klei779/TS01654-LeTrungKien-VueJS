private void initStatusComboBox() {
        String[] statuses = {"OPERATING", "LOST", "ERROR", "UNKNOWN"};
        cboStatus.setModel(new DefaultComboBoxModel<>(statuses));
    }

    private void loadData() {
        try {
            cardList = dao.selectAll();
            if (cardList == null) cardList = new ArrayList<>();
            if (!cardList.isEmpty()) {
                currentIndex = 0;
                setForm(cardList.get(currentIndex));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi tải dữ liệu: " + e.getMessage());
        }
    }

    public void setForm(Card card) {
        if (card == null) return;
        txtId.setText(String.valueOf(card.getId()));
        txtId.setEditable(false); // Không cho sửa ID khi update
        cboStatus.setSelectedIndex(card.getStatus());
    }

    public Card getForm() {
        try {
            int id = Integer.parseInt(txtId.getText().trim());
            if (id <= 0) {
                JOptionPane.showMessageDialog(this, "Mã thẻ phải lớn hơn 0!");
                return null;
            }

            int status = cboStatus.getSelectedIndex();
            if (status < 0 || status > 3) {
                JOptionPane.showMessageDialog(this, "Trạng thái không hợp lệ!");
                return null;
            }

            return new Card(id, status);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Mã thẻ phải là số nguyên!");
            return null;
        }
    }

    private void updateCard() {
    Card card = getForm();
    if (card != null) {
        try {
            dao.update(card);
            JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
            if (cardPanel != null) {
                cardPanel.fillTable();
                cardPanel.moveTo(currentIndex);
            }
            dispose(); // Đóng dialog ngay sau khi cập nhật
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi cập nhật: " + e.getMessage());
        }
    }
}


    // ====== Điều hướng ======
    private void moveFirst() {
        if (cardList.isEmpty()) return;
        currentIndex = 0;
        setForm(cardList.get(currentIndex));
        if (cardPanel != null) cardPanel.moveTo(currentIndex);
    }

    private void movePrevious() {
        if (cardList.isEmpty()) return;
        currentIndex = (currentIndex <= 0) ? cardList.size() - 1 : currentIndex - 1;
        setForm(cardList.get(currentIndex));
        if (cardPanel != null) cardPanel.moveTo(currentIndex);
    }

    private void moveNext() {
        if (cardList.isEmpty()) return;
        currentIndex = (currentIndex >= cardList.size() - 1) ? 0 : currentIndex + 1;
        setForm(cardList.get(currentIndex));
        if (cardPanel != null) cardPanel.moveTo(currentIndex);
    }

    private void moveLast() {
        if (cardList.isEmpty()) return;
        currentIndex = cardList.size() - 1;
        setForm(cardList.get(currentIndex));
        if (cardPanel != null) cardPanel.moveTo(currentIndex);
    }


// ======================== KHỞI TẠO ==========================
    private void init() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"Mã số", "Thẻ phiếu", "Thời điểm tại", "Thời điểm thanh toán", "Loại hình thanh toán", "Trạng thái", "Chọn"}, 0) {

            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 6 ? Boolean.class : String.class; // Cột cuối là checkbox
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 6; // Chỉ cho tick chọn ở cột cuối
            }
        };
        tblBillManager.setModel(model);
        fillTable(); // nạp bảng ban đầu
    }

// ======================== ĐỔ DỮ LIỆU VÀO BẢNG ==========================
    private void fillTable() {
        List<Bill> list = billDAO.selectAll(); // sau này có thể lọc theo ngày, category...
        DefaultTableModel model = (DefaultTableModel) tblBillManager.getModel();
        model.setRowCount(0);
        try {
            for (Bill b : list) {
                model.addRow(new Object[]{
                    b.getId(),
                    b.getCardId() != null ? b.getCardId().toString() : "",
                    formatDate(b.getCheckIn()),
                    formatDate(b.getCheckOut()),
                    getPaymentMethodText(b.getPaymentMethod()),
                    b.getStatus() ? "Đã thanh toán" : "Chưa thanh toán",
                    false
                });
            }
        } catch (Exception e) {
            MsgBox.alert(this, "Lỗi truy cập dữ liệu: " + e.getMessage());
        }
    }

// ======================== THÊM HÓA ĐƠN ==========================
    private void insertBill() {
        BillManagerAddJDialog dialog = new BillManagerAddJDialog(null, true);
        dialog.setVisible(true);

        if (dialog.isConfirmed()) {
            Bill bill = dialog.getBill();
            List<BillDetails> details = dialog.getBillDetails();

            if (bill != null && details != null) {
                try {
                    billDAO.insert(bill);
                    for (BillDetails d : details) {
                        billDetailDAO.insert(d);
                    }
                    MsgBox.alert(this, "Thêm hóa đơn thành công!");
                    fillTable();
                } catch (Exception e) {
                    MsgBox.alert(this, "Lỗi khi thêm hóa đơn: " + e.getMessage());
                }
            }
        }
    }

// ======================== CẬP NHẬT HÓA ĐƠN ==========================
    private void updateBill() {
        int row = tblBillManager.getSelectedRow();
        if (row == -1) {
            MsgBox.alert(this, "Vui lòng chọn một hóa đơn để cập nhật.");
            return;
        }

        int billId = Integer.parseInt(tblBillManager.getValueAt(row, 0).toString());
        Bill bill = billDAO.selectByID(billId);
        List<BillDetails> details = billDetailDAO.selectByBillId(billId);

        if (bill == null || details.isEmpty()) {
            MsgBox.alert(this, "Không tìm thấy dữ liệu hóa đơn.");
            return;
        }

        BillManagerUpdateJDialog dialog = new BillManagerUpdateJDialog(null, true);
        dialog.setForm(bill, details);
        dialog.setVisible(true);

        if (dialog.isConfirmed()) {
            Bill updatedBill = dialog.getBill();
            List<BillDetails> updatedDetails = dialog.getBillDetails();

            if (updatedBill != null && updatedDetails != null) {
                try {
                    billDAO.update(updatedBill);
                    billDetailDAO.delete(updatedBill.getId());
                    for (BillDetails d : updatedDetails) {
                        billDetailDAO.insert(d);
                    }
                    MsgBox.alert(this, "Cập nhật hóa đơn thành công!");
                    fillTable();
                } catch (Exception e) {
                    MsgBox.alert(this, "Lỗi khi cập nhật hóa đơn: " + e.getMessage());
                }
            }
        }
    }

// ======================== XÓA HÓA ĐƠN ==========================
    private void deleteBill() {
        if (!MsgBox.confirm(this, "Bạn có chắc muốn xóa các hóa đơn đã chọn?")) {
            return;
        }

        boolean deletedAny = false;
        DefaultTableModel model = (DefaultTableModel) tblBillManager.getModel();

        for (int i = model.getRowCount() - 1; i >= 0; i--) {
            Boolean selected = (Boolean) model.getValueAt(i, 6);
            if (Boolean.TRUE.equals(selected)) {
                int id = Integer.parseInt(model.getValueAt(i, 0).toString());
                try {
                    billDetailDAO.delete(id);
                    billDAO.delete(id);
                    deletedAny = true;
                } catch (Exception e) {
                    MsgBox.alert(this, "Lỗi xóa ID " + id + ": " + e.getMessage());
                }
            }
        }

        MsgBox.alert(this, deletedAny ? "Xóa thành công." : "Không có hóa đơn nào được chọn.");
        fillTable();
    }


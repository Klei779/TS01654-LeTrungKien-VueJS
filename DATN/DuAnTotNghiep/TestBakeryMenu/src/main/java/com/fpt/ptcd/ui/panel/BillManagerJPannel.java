    private void moveFirst() {
        moveTo(0);
    }

    private void movePrevious() {
        moveTo(tblBillManager.getSelectedRow() - 1);
    }

    private void moveNext() {
        moveTo(tblBillManager.getSelectedRow() + 1);
    }

    private void moveLast() {
        moveTo(tblBillManager.getRowCount() - 1);
    }

    private void moveTo(int index) {
        int rowCount = tblBillManager.getRowCount();
        if (rowCount == 0) {
            return;
        }

        if (index < 0) {
            index = rowCount - 1;
        }
        if (index >= rowCount) {
            index = 0;
        }

        tblBillManager.clearSelection();
        tblBillManager.setRowSelectionInterval(index, index);
    }

